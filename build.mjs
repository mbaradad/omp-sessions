import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as path from "node:path";

const watch = process.argv.includes("--watch");
const production = process.argv.includes("--production");
const common = { bundle: true, sourcemap: !production, minify: production, logLevel: "info", target: "es2022" };
const builds = [
	{ ...common, entryPoints: ["src/ext/extension.ts"], outfile: "out/extension.js", platform: "node", format: "cjs", external: ["vscode"] },
	{ ...common, entryPoints: ["src/graph/main.ts"], outfile: "out/graph.js", platform: "browser", format: "iife" },
	{ ...common, entryPoints: ["src/graph/style.css"], outfile: "out/graph.css" },
	{ ...common, entryPoints: ["src/webview/main.ts"], outfile: "out/webview.js", platform: "browser", format: "iife" },
	{ ...common, entryPoints: ["src/webview/style.css"], outfile: "out/webview.css" },
	{ ...common, entryPoints: ["src/bridge/mcp.ts"], outfile: "out/mcp.js", platform: "node", format: "cjs" },
	// omp extensions shipped with Switchyard: every module in src/omp-extension/ (checkpoints, mode, todos, …); src/ext/omp-extension.ts installs them.
	{ ...common, sourcemap: false, entryPoints: fs.readdirSync("src/omp-extension").filter(f => f.endsWith(".ts")).map(f => `src/omp-extension/${f}`), outdir: "out/omp-extension", platform: "node", format: "esm" },
	{ ...common, entryPoints: ["src/kanban/main.ts"], outfile: "out/kanban.js", platform: "browser", format: "iife" },
	{ ...common, entryPoints: ["src/kanban/style.css"], outfile: "out/kanban.css" },
	{ ...common, entryPoints: ["src/planner/main.ts"], outfile: "out/planner.js", platform: "node", format: "cjs", define: { PLANNER_VERSION: JSON.stringify(JSON.parse(fs.readFileSync("package.json", "utf8")).version) } },
	{ ...common, entryPoints: ["src/cli/main.ts"], outfile: "out/cli.js", platform: "node", format: "cjs", banner: { js: "#!/usr/bin/env node" } },
];
/** Files used next to the bundles as they are: the agent skill, the omp shim. */
const copies = [
	["skills/switchyard/SKILL.md", "out/switchyard.SKILL.md"],
	// Switchyard's `omp` shim (extra omp flags for AO sessions, G34); src/shared/omp-extension-install.ts installs it.
	["src/omp-shim/omp", "out/omp-shim/omp"],
];

fs.rmSync("out", { recursive: true, force: true });
fs.mkdirSync("out", { recursive: true });
for (const [from, to] of copies) {
	fs.mkdirSync(path.dirname(to), { recursive: true });
	fs.copyFileSync(from, to);
}
// The Hermes plugin folder is published as is (`hermes plugins install …/integrations/hermes/switchyard`
// fetches only that folder), so it carries a committed copy of the skill; keep it in sync.
const PLUGIN = "integrations/hermes/switchyard";
const pluginSkill = `${PLUGIN}/skills/switchyard/SKILL.md`;
const skill = fs.readFileSync("skills/switchyard/SKILL.md", "utf8");
if (!fs.existsSync(pluginSkill) || fs.readFileSync(pluginSkill, "utf8") !== skill) {
	fs.mkdirSync(`${PLUGIN}/skills/switchyard`, { recursive: true });
	fs.writeFileSync(pluginSkill, skill);
}
const { version } = JSON.parse(fs.readFileSync("package.json", "utf8"));
const pluginVersion = /^version:\s*(\S+)/m.exec(fs.readFileSync(`${PLUGIN}/plugin.yaml`, "utf8"))?.[1];
if (pluginVersion !== version) throw new Error(`${PLUGIN}/plugin.yaml version ${pluginVersion} ≠ package.json ${version}`);
const dashboardVersion = JSON.parse(fs.readFileSync(`${PLUGIN}/dashboard/manifest.json`, "utf8")).version;
if (dashboardVersion !== version) throw new Error(`${PLUGIN}/dashboard/manifest.json version ${dashboardVersion} ≠ package.json ${version}`);
// The Switchyard page for the Hermes dashboard (an IIFE + CSS) and Hermes Desktop (an ES module that
// imports only what Desktop provides), from integrations/hermes/ui into the plugin folder. They are
// committed (installs fetch the folder with no build step) and stay readable: never minified, no
// source maps, React from the host.
const generated = "Generated by build.mjs from integrations/hermes/ui; edit the sources there.";
// PAGE_VERSION lets the Desktop page notice it is older than the plugin backend it talks to.
const hermesUi = { bundle: true, minify: false, sourcemap: false, target: "es2022", logLevel: "info", platform: "browser", charset: "utf8", define: { PAGE_VERSION: JSON.stringify(version) } };
const hermesUiBuilds = [
	{ ...hermesUi, entryPoints: ["integrations/hermes/ui/dashboard.ts"], outfile: `${PLUGIN}/dashboard/dist/index.js`, format: "iife", banner: { js: `// Switchyard dashboard tab. ${generated}` } },
	{ ...hermesUi, entryPoints: ["integrations/hermes/ui/style.css"], outfile: `${PLUGIN}/dashboard/dist/style.css`, banner: { css: `/* Switchyard dashboard tab. ${generated} */` } },
	{
		...hermesUi,
		entryPoints: ["integrations/hermes/ui/desktop.ts"],
		outfile: `${PLUGIN}/desktop/plugin.js`,
		format: "esm",
		external: ["@hermes/plugin-sdk", "react", "react/jsx-runtime"],
		loader: { ".css": "text" },
		banner: { js: `// Switchyard page for Hermes Desktop. ${generated}` },
	},
];
if (watch) {
	for (const b of hermesUiBuilds) await (await esbuild.context(b)).watch();
} else {
	await Promise.all(hermesUiBuilds.map(b => esbuild.build(b)));
}
// `switchyard hermes install` copies the plugin from the runtime folder into Hermes.
fs.cpSync(PLUGIN, "out/hermes-plugin/switchyard", { recursive: true, filter: f => !f.includes("__pycache__") });
if (watch) {
	for (const b of builds) await (await esbuild.context(b)).watch();
} else {
	await Promise.all(builds.map(b => esbuild.build(b)));
}
